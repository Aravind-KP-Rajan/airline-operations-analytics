-- Confirm one row per airport ID and check descriptive fields.
SELECT
    COUNT(*) AS AIRPORT_ROWS,
    COUNT(DISTINCT AIRPORT_ID) AS UNIQUE_AIRPORT_IDS,
    COUNT_IF(
        AIRPORT_ID IS NULL
        OR AIRPORT_CODE IS NULL
        OR CITY_NAME IS NULL
    ) AS ROWS_WITH_MISSING_DETAILS
FROM AIRLINE_DB.ANALYTICS.DIM_AIRPORT;


-- Store one row per BTS reported flight.
CREATE TABLE AIRLINE_DB.ANALYTICS.FACT_FLIGHTS AS
SELECT
    -- Keys connecting each flight to the dimensions.
    FLIGHT_DATE AS DATE_KEY,
    CARRIER_CODE,
    ORIGIN_AIRPORT_ID,
    DEST_AIRPORT_ID,

    -- Flight identity and schedule.
    OP_CARRIER_FL_NUM AS FLIGHT_NUMBER,
    TAIL_NUM AS TAIL_NUMBER,
    CRS_DEP_TIME,
    DEP_TIME,
    CRS_ARR_TIME,
    ARR_TIME,

    -- Operational measures.
    DEP_DELAY,
    ARR_DELAY,
    DEP_DEL15,
    ARR_DEL15,
    CRS_ELAPSED_TIME,
    ACTUAL_ELAPSED_TIME,
    AIR_TIME,
    DISTANCE,

    -- Disruption status and reported cause minutes.
    CANCELLED,
    CANCELLATION_CODE,
    DIVERTED,
    CARRIER_DELAY,
    WEATHER_DELAY,
    NAS_DELAY,
    SECURITY_DELAY,
    LATE_AIRCRAFT_DELAY,

    -- Only flights that operated and were not diverted qualify for arrival OTP.
    CASE
        WHEN CANCELLED = 0 AND DIVERTED = 0 THEN 1
        ELSE 0
    END AS ARRIVAL_ELIGIBLE_FLAG,

    -- Keep ineligible flights NULL rather than calling them on-time or late.
    CASE
        WHEN CANCELLED = 0 AND DIVERTED = 0 AND ARR_DELAY < 15 THEN 1
        WHEN CANCELLED = 0 AND DIVERTED = 0 THEN 0
        ELSE NULL
    END AS ARRIVAL_ON_TIME_FLAG

FROM AIRLINE_DB.STAGING.FLIGHTS_CLEAN;


-- Verify flight count and the arrival OTP flags.
SELECT
    COUNT(*) AS FACT_ROWS,
    SUM(ARRIVAL_ELIGIBLE_FLAG) AS ELIGIBLE_ARRIVALS,
    COUNT_IF(
        ARRIVAL_ELIGIBLE_FLAG = 1
        AND ARRIVAL_ON_TIME_FLAG IS NULL
    ) AS ELIGIBLE_WITHOUT_OTP_FLAG,
    COUNT_IF(
        ARRIVAL_ELIGIBLE_FLAG = 0
        AND ARRIVAL_ON_TIME_FLAG IS NOT NULL
    ) AS INELIGIBLE_WITH_OTP_FLAG,
    COUNT_IF(
        ARRIVAL_ELIGIBLE_FLAG = 1
        AND ARRIVAL_ON_TIME_FLAG <> 1 - ARR_DEL15
    ) AS BTS_FLAG_MISMATCHES
FROM AIRLINE_DB.ANALYTICS.FACT_FLIGHTS;



-- Check that every flight can link to its date, carrier, and two airports.
SELECT
    COUNT(*) AS JOINED_FLIGHTS,
    COUNT_IF(D.DATE_KEY IS NULL) AS MISSING_DATE,
    COUNT_IF(A.CARRIER_CODE IS NULL) AS MISSING_AIRLINE,
    COUNT_IF(O.AIRPORT_ID IS NULL) AS MISSING_ORIGIN,
    COUNT_IF(T.AIRPORT_ID IS NULL) AS MISSING_DESTINATION
FROM AIRLINE_DB.ANALYTICS.FACT_FLIGHTS AS F
LEFT JOIN AIRLINE_DB.ANALYTICS.DIM_DATE AS D
    ON F.DATE_KEY = D.DATE_KEY
LEFT JOIN AIRLINE_DB.ANALYTICS.DIM_AIRLINE AS A
    ON F.CARRIER_CODE = A.CARRIER_CODE
LEFT JOIN AIRLINE_DB.ANALYTICS.DIM_AIRPORT AS O
    ON F.ORIGIN_AIRPORT_ID = O.AIRPORT_ID
LEFT JOIN AIRLINE_DB.ANALYTICS.DIM_AIRPORT AS T
    ON F.DEST_AIRPORT_ID = T.AIRPORT_ID;