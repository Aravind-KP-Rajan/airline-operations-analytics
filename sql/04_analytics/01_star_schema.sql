-- Measure the number of carriers and airports represented in STAGING.
SELECT
    COUNT(DISTINCT CARRIER_CODE) AS CARRIERS,
    COUNT(DISTINCT ORIGIN_AIRPORT_ID) AS ORIGIN_AIRPORTS,
    COUNT(DISTINCT DEST_AIRPORT_ID) AS DESTINATION_AIRPORTS
FROM AIRLINE_DB.STAGING.FLIGHTS_CLEAN;


-- One row per distinct flight date in the 2024 source data.
CREATE TABLE AIRLINE_DB.ANALYTICS.DIM_DATE AS
SELECT DISTINCT
    FLIGHT_DATE AS DATE_KEY,
    YEAR(FLIGHT_DATE) AS CALENDAR_YEAR,
    QUARTER(FLIGHT_DATE) AS CALENDAR_QUARTER,
    MONTH(FLIGHT_DATE) AS MONTH_NUMBER,
    DAY(FLIGHT_DATE) AS DAY_OF_MONTH,
    DAYOFWEEKISO(FLIGHT_DATE) AS ISO_DAY_OF_WEEK,
    WEEKISO(FLIGHT_DATE) AS ISO_WEEK_NUMBER,
    YEAROFWEEKISO(FLIGHT_DATE) AS ISO_WEEK_YEAR
FROM AIRLINE_DB.STAGING.FLIGHTS_CLEAN;

-- Confirm one dimension row per date across all of 2024.
SELECT
    COUNT(*) AS DATE_ROWS,
    COUNT(DISTINCT DATE_KEY) AS UNIQUE_DATES,
    MIN(DATE_KEY) AS FIRST_DATE,
    MAX(DATE_KEY) AS LAST_DATE
FROM AIRLINE_DB.ANALYTICS.DIM_DATE;


-- Find carrier codes linked to more than one BTS airline ID.
SELECT
    CARRIER_CODE,
    COUNT(DISTINCT OP_CARRIER_AIRLINE_ID) AS AIRLINE_IDS
FROM AIRLINE_DB.STAGING.FLIGHTS_CLEAN
GROUP BY CARRIER_CODE
HAVING COUNT(DISTINCT OP_CARRIER_AIRLINE_ID) > 1;


-- Keep one row per reporting operating carrier.
CREATE TABLE AIRLINE_DB.ANALYTICS.DIM_AIRLINE AS
SELECT DISTINCT
    CARRIER_CODE,
    OP_CARRIER_AIRLINE_ID AS AIRLINE_ID
FROM AIRLINE_DB.STAGING.FLIGHTS_CLEAN;


-- Confirm one dimension row per reporting carrier code.
SELECT
    COUNT(*) AS AIRLINE_ROWS,
    COUNT(DISTINCT CARRIER_CODE) AS UNIQUE_CARRIER_CODES,
    COUNT_IF(CARRIER_CODE IS NULL OR AIRLINE_ID IS NULL) AS MISSING_KEYS
FROM AIRLINE_DB.ANALYTICS.DIM_AIRLINE;


-- Put origin and destination airport details into one temporary result.
WITH AIRPORT_RECORDS AS (
    SELECT
        ORIGIN_AIRPORT_ID AS AIRPORT_ID,
        ORIGIN AS AIRPORT_CODE,
        ORIGIN_CITY_NAME AS CITY_NAME
    FROM AIRLINE_DB.STAGING.FLIGHTS_CLEAN

    UNION ALL

    SELECT
        DEST_AIRPORT_ID AS AIRPORT_ID,
        DEST AS AIRPORT_CODE,
        DEST_CITY_NAME AS CITY_NAME
    FROM AIRLINE_DB.STAGING.FLIGHTS_CLEAN
)
SELECT
    AIRPORT_ID,
    COUNT(DISTINCT AIRPORT_CODE) AS DISTINCT_CODES,
    COUNT(DISTINCT CITY_NAME) AS DISTINCT_CITIES
FROM AIRPORT_RECORDS
GROUP BY AIRPORT_ID
HAVING COUNT(DISTINCT AIRPORT_CODE) > 1
    OR COUNT(DISTINCT CITY_NAME) > 1;


    -- Combine origin and destination airports into one dimension.
CREATE TABLE AIRLINE_DB.ANALYTICS.DIM_AIRPORT AS
SELECT
    ORIGIN_AIRPORT_ID AS AIRPORT_ID,
    ORIGIN AS AIRPORT_CODE,
    ORIGIN_CITY_NAME AS CITY_NAME
